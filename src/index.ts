import React from 'react';
import {
  registerRoot,
  Composition,
  Sequence,
  Audio,
  staticFile,
  useCurrentFrame,
  AbsoluteFill,
} from 'remotion';
import {Classroom3D} from './three/Classroom3D';

const E = React.createElement;

type Speaker = 'teacher' | 'student' | 'silent';

interface StoryScene {
  text?: string;
  arabic?: string;
  speaker?: string;
  durationInSeconds?: number;
}

const SceneView: React.FC<{
  text: string;
  arabic?: string;
  speaker: Speaker;
  frames: number;
}> = ({text, arabic, speaker, frames}) => {
  const frame = useCurrentFrame();
  const rtl = /[\u0600-\u06FF]/.test(text);
  const count = speaker === 'silent'
    ? Math.max(1, Math.ceil((frames - frame) / 30))
    : undefined;
  const label = speaker === 'student'
    ? 'طالب علم'
    : speaker === 'silent'
      ? 'سوچنے کا وقت'
      : 'استاد';
  const accent = speaker === 'student' ? '#6ac7f2' : '#f2c76b';

  return E(AbsoluteFill, {
    style: {
      backgroundColor: '#07140f',
      overflow: 'hidden',
    },
  },
    // Real 3D classroom scene. All animation is driven by Remotion frames.
    E(Classroom3D, {speaker}),

    // Contrast overlay for readable Urdu captions.
    E(AbsoluteFill, {
      style: {
        pointerEvents: 'none',
        background: 'linear-gradient(180deg, rgba(3,10,7,0.38) 0%, rgba(3,10,7,0.02) 36%, rgba(3,10,7,0.08) 55%, rgba(3,10,7,0.90) 100%)',
      },
    }),

    // Optional verified Arabic text at the top.
    E('div', {
      style: {
        position: 'absolute',
        top: 58,
        left: 48,
        right: 48,
        minHeight: 100,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        pointerEvents: 'none',
      },
    },
      arabic
        ? E('div', {
            dir: 'rtl',
            style: {
              fontFamily: "'Noto Naskh Arabic', serif",
              fontSize: 44,
              lineHeight: 1.7,
              color: '#ffe2a0',
              fontWeight: 700,
              textAlign: 'center',
              backgroundColor: 'rgba(3,10,7,0.66)',
              border: '1px solid rgba(242,199,107,0.55)',
              borderRadius: 22,
              padding: '12px 26px',
            },
          }, arabic)
        : null
    ),

    // Five-to-one thinking countdown.
    count !== undefined
      ? E('div', {
          style: {
            position: 'absolute',
            left: '50%',
            top: '49%',
            transform: 'translate(-50%, -50%)',
            width: 156,
            height: 156,
            borderRadius: '50%',
            border: '6px solid #f2c76b',
            backgroundColor: 'rgba(5,17,12,0.88)',
            boxShadow: '0 0 38px rgba(242,199,107,0.42)',
            color: '#ffe2a0',
            fontFamily: 'Arial, sans-serif',
            fontSize: 88,
            fontWeight: 800,
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
            pointerEvents: 'none',
          },
        }, String(count))
      : null,

    // Large bottom caption panel.
    E('div', {
      style: {
        position: 'absolute',
        left: 42,
        right: 42,
        bottom: 72,
        backgroundColor: 'rgba(5,17,12,0.94)',
        border: `2px solid ${accent}`,
        borderRadius: 30,
        padding: '24px 30px 30px',
        boxSizing: 'border-box',
        textAlign: 'center',
        boxShadow: '0 14px 38px rgba(0,0,0,0.36)',
        pointerEvents: 'none',
      },
    },
      E('div', {
        dir: 'rtl',
        style: {
          display: 'inline-block',
          backgroundColor: accent,
          color: '#07140f',
          fontFamily: "'Noto Nastaliq Urdu', sans-serif",
          fontSize: 28,
          fontWeight: 800,
          padding: '4px 24px 9px',
          borderRadius: 999,
          marginBottom: 12,
        },
      }, label),
      E('div', {
        dir: rtl ? 'rtl' : 'ltr',
        style: {
          fontFamily: rtl ? "'Noto Nastaliq Urdu', serif" : 'Arial, sans-serif',
          fontSize: rtl ? 48 : 44,
          lineHeight: rtl ? 1.95 : 1.35,
          fontWeight: 700,
          color: '#ffffff',
          overflowWrap: 'anywhere',
        },
      }, text)
    )
  );
};

const MainVideo: React.FC<{scenes?: StoryScene[]}> = ({scenes = []}) => {
  let currentFrame = 0;

  return E(AbsoluteFill, {style: {backgroundColor: '#000000'}},
    // Existing Urdu voiceover generated by the GitHub Actions workflow.
    E(Audio, {src: staticFile('voiceover.mp3')}),
    scenes.map((scene, index) => {
      const seconds = Number(scene.durationInSeconds) || 5;
      const durationInFrames = Math.max(15, Math.round(seconds * 30));
      const from = currentFrame;
      currentFrame += durationInFrames;

      const speaker: Speaker = scene.speaker === 'student' || scene.speaker === 'silent'
        ? scene.speaker
        : 'teacher';

      return E(Sequence, {
        key: index,
        from,
        durationInFrames,
      },
        E(SceneView, {
          text: String(scene.text || ''),
          arabic: scene.arabic,
          speaker,
          frames: durationInFrames,
        })
      );
    })
  );
};

export const RemotionRoot: React.FC = () => E(Composition, {
  id: 'IslamicVideo',
  component: MainVideo,
  durationInFrames: 150,
  fps: 30,
  width: 1080,
  height: 1920,
  defaultProps: {scenes: []},
  calculateMetadata: async () => {
    const response = await fetch(staticFile('story.json'));
    if (!response.ok) {
      throw new Error(`Unable to load story.json: HTTP ${response.status}`);
    }

    const data = await response.json();
    const scenes: StoryScene[] = Array.isArray(data?.scenes) ? data.scenes : [];
    const totalSeconds = scenes.reduce(
      (sum, scene) => sum + (Number(scene.durationInSeconds) || 5),
      0
    );

    return {
      durationInFrames: Math.max(30, Math.round(totalSeconds * 30)),
      props: {scenes},
    };
  },
});

registerRoot(RemotionRoot);
